#!/usr/bin/env bash
# Generate random secrets for the local Docker Compose stack.
#
# Usage: scripts/generate-compose-secrets.sh [output-directory]
# The directory defaults to compose-secrets/, which git ignores. Each service gets its
# own file, so the database container never sees the API's keys:
#   db   PostgreSQL credentials
#   api  database URL, JWT signing key and Fernet encryption key
# The directory is created owner-only and must not exist yet. Nothing secret is
# printed.
set -euo pipefail

readonly output_dir="${1:-compose-secrets}"
readonly postgres_user="vault"
readonly postgres_db="vault"
readonly postgres_password_bytes=24
readonly jwt_secret_bytes=48
readonly fernet_key_bytes=32

# URL-safe base64 of N random bytes; padding is kept, because Fernet keys need it.
random_urlsafe() {
  head -c "$1" /dev/urandom | base64 | tr -d '\n' | tr '+/' '-_'
}

# mkdir without -p fails on anything already at the path, dangling symlinks included.
if ! mkdir -m 700 "$output_dir" 2>/dev/null; then
  cat >&2 <<EOF
error: $output_dir already exists.
To start over, run 'docker compose down --volumes' first and then delete $output_dir:
the database keeps its original password, and items encrypted under the old
Fernet key cannot be decrypted with a new one. Both are lost on purpose.
EOF
  exit 1
fi

postgres_password="$(random_urlsafe "$postgres_password_bytes" | tr -d '=')"
jwt_secret="$(random_urlsafe "$jwt_secret_bytes" | tr -d '=')"
fernet_key="$(random_urlsafe "$fernet_key_bytes")"

umask 077
set -o noclobber

cat >"$output_dir/db" <<EOF
# Generated by scripts/generate-compose-secrets.sh. Never commit this file.
POSTGRES_USER=${postgres_user}
POSTGRES_DB=${postgres_db}
POSTGRES_PASSWORD=${postgres_password}
EOF

cat >"$output_dir/api" <<EOF
# Generated by scripts/generate-compose-secrets.sh. Never commit this file.
VAULT_DATABASE_URL=postgresql+asyncpg://${postgres_user}:${postgres_password}@db:5432/${postgres_db}
VAULT_JWT_SECRET_KEY=${jwt_secret}
VAULT_FERNET_KEYS=${fernet_key}
EOF

echo "Wrote $output_dir/. Start the stack with: docker compose up --build"
